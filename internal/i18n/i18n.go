package i18n

import (
	"fmt"
	"net/http"
	"os"
	"strings"
	"sync"
)

var preferred struct {
	sync.RWMutex
	value string
}

// SetPreferred selects a supported UI language or auto for native desktop UI.
func SetPreferred(value string) {
	value = strings.TrimSpace(value)
	if !isSupportedLanguage(value) {
		value = "auto"
	}
	preferred.Lock()
	preferred.value = value
	preferred.Unlock()
}

const (
	ZH = "zh-CN"
	EN = "en"
)

// Supported reports whether value is one of the shipped UI languages. Callers
// outside this package use it to tell "the caller named a language we have"
// from "fall back", which is not the same as Normalize returning EN — Normalize
// answers EN for unknown input too.
func Supported(value string) bool { return isSupportedLanguage(value) }

func isSupportedLanguage(value string) bool {
	switch value {
	case EN, ZH, "zh-TW", "ja", "ko", "es", "fr", "de":
		return true
	default:
		return false
	}
}

